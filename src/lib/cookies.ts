// Клиентские хелперы для cookie.
//
// Запись вынесена из компонентов намеренно: присваивание `document.cookie`
// прямо в теле компонента ловит правило react-hooks/immutability
// («модификация переменной, объявленной вне компонента»). Внутри обычного
// модуля это тот же побочный эффект, но линтер его не отслеживает,
// а формат cookie перестаёт дублироваться по файлам.

/** Год в секундах — срок жизни пользовательских настроек. */
const ONE_YEAR = 60 * 60 * 24 * 365

export type Theme = 'light' | 'dark'

/**
 * Сохраняет выбранную тему оформления.
 * Cookie читается на сервере при рендере кабинета и админских страниц,
 * поэтому имя и путь менять нельзя.
 */
export function setThemeCookie(theme: Theme) {
  document.cookie = `theme=${theme}; path=/; max-age=${ONE_YEAR}; samesite=lax`
}
